@dataclass
class Entry:
    kind: str
    label: str
    key: Optional[str] = None
    submenu: Optional[str] = None


def menu_entries(menu: str, cfg: Dict[str, str]) -> List[Entry]:
    if menu == "root":
        return [
            Entry("submenu", "General setup", submenu="general"),
            Entry("submenu", "Machine profile", submenu="machine"),
            Entry("submenu", "Expansion support", submenu="expansion"),
            Entry("submenu", "Media loaders", submenu="media"),
            Entry("submenu", "Build identification", submenu="id"),
            Entry("action", "Save configuration"),
            Entry("action", "Load configuration"),
            Entry("action", "Exit"),
        ]
    if menu == "general":
        return [
            Entry("bool", "Ativar DEBUG", key="DEBUG"),
            Entry("choice", "Boot Mode default", key="MSXBARE_BOOT_MODE_DEFAULT"),
        ]
    if menu == "machine":
        entries = [
            Entry("bool", "Suporte a MSX2", key="MSXBARE_FEAT_MSX2"),
            Entry("bool", "Suporte a MSX2+", key="MSXBARE_FEAT_MSX2P"),
            Entry("bool", "One ROM Mode", key="MSXBARE_ONE_ROM_MODE"),
            Entry("string", "One ROM path", key="MSXBARE_ONE_ROM_PATH"),
        ]
        return entries
    if menu == "expansion":
        return [
            Entry("bool", "Suporte a SCC", key="MSXBARE_FEAT_SCC"),
            Entry("bool", "Suporte a FM-PAC", key="MSXBARE_FEAT_FMPAC"),
            Entry("bool", "Suporte a DISK ROM", key="MSXBARE_FEAT_DISK_ROM"),
            Entry("bool", "Suporte a MegaRAM", key="MSXBARE_FEAT_MEGARAM"),
        ]
    if menu == "media":
        return [
            Entry("bool", "Suporte a LOAD ROM", key="MSXBARE_FEAT_LOAD_ROM"),
            Entry("bool", "Suporte a LOAD DISK", key="MSXBARE_FEAT_LOAD_DISK"),
        ]
    if menu == "id":
        return [
            Entry("string", "Patreon / Owner tag", key="MSXBARE_PATREON_TAG"),
        ]
    return []


def fmt_entry(e: Entry, cfg: Dict[str, str]) -> str:
    if e.kind == "submenu":
        return f"{e.label}  --->"
    if e.kind == "bool" and e.key:
        checked = "*" if cfg.get(e.key) == "1" else " "
        return f"[{checked}] {e.label}"
    if e.kind == "choice" and e.key:
        return f"({cfg.get(e.key, '')}) {e.label}"
    if e.kind == "string" and e.key:
        value = cfg.get(e.key, "")
        if not value:
            value = "<empty>"
        return f"({value}) {e.label}"
    return e.label


def prompt_string(stdscr, title: str, initial: str) -> str:
    h, w = stdscr.getmaxyx()
    win_h, win_w = 7, min(max(60, len(title) + 8), w - 4)
    y = max(1, (h - win_h) // 2)
    x = max(2, (w - win_w) // 2)
    win = curses.newwin(win_h, win_w, y, x)
    win.box()
    win.addstr(1, 2, title[: win_w - 4])
    win.addstr(3, 2, "Value: ")
    curses.echo()
    curses.curs_set(1)
    win.addstr(3, 9, " " * (win_w - 11))
    win.addstr(3, 9, initial[: win_w - 11])
    win.refresh()
    inp = win.getstr(3, 9, win_w - 11)
    curses.noecho()
    curses.curs_set(0)
    return inp.decode("utf-8", errors="ignore")


def popup(stdscr, title: str, text: str) -> None:
    lines = text.splitlines() or [""]
    h, w = stdscr.getmaxyx()
    inner_w = max(len(title), max(len(l) for l in lines), 20)
    win_w = min(inner_w + 4, w - 4)
    win_h = min(len(lines) + 4, h - 4)
    y = max(1, (h - win_h) // 2)
    x = max(2, (w - win_w) // 2)
    win = curses.newwin(win_h, win_w, y, x)
    win.box()
    win.addstr(0, 2, f" {title} "[: win_w - 3], curses.A_BOLD)
    for i, line in enumerate(lines[: win_h - 4]):
        win.addstr(i + 2, 2, line[: win_w - 4])
    win.addstr(win_h - 2, 2, "Press any key")
    win.refresh()
    win.getch()


def run_tui(stdscr, cfg: Dict[str, str]) -> Dict[str, str]:
    curses.curs_set(0)
    stdscr.keypad(True)

    stack = ["root"]
    selected = {"root": 0}

    while True:
        menu = stack[-1]
        entries = menu_entries(menu, cfg)
        idx = selected.get(menu, 0)
        idx = max(0, min(idx, max(0, len(entries) - 1)))
        selected[menu] = idx

        stdscr.erase()
        h, w = stdscr.getmaxyx()

        title = "MSX BarePI - Build Configuration"
        legend = "Arrows: navigate  Enter: select submenu/value  Y/N or Space: toggle  S: Save  L: Load  ?: Help  Esc: Back"
        stdscr.addstr(0, 0, title[: w - 1], curses.A_REVERSE)
        stdscr.addstr(1, 0, legend[: w - 1])
        stdscr.hline(2, 0, ord('-'), w)

        y = 4
        for i, e in enumerate(entries):
            attr = curses.A_REVERSE if i == idx else curses.A_NORMAL
            text = fmt_entry(e, cfg)
            stdscr.addstr(y + i, 2, text[: w - 4], attr)

        footer = "<Select>   < Exit >   < Help >   < Save >   < Load >"
        stdscr.hline(h - 3, 0, ord('-'), w)
        stdscr.addstr(h - 2, max(0, (w - len(footer)) // 2), footer[: w - 1], curses.A_BOLD)
        stdscr.refresh()

        ch = stdscr.getch()
        if ch in (curses.KEY_UP, ord('k')):
            selected[menu] = max(0, idx - 1)
            continue
        if ch in (curses.KEY_DOWN, ord('j')):
            selected[menu] = min(len(entries) - 1, idx + 1)
            continue
        if ch in (27, curses.KEY_LEFT):
            if len(stack) > 1:
                stack.pop()
                continue
            return cfg
        if ch in (ord('s'), ord('S')):
            write_outputs(cfg)
            popup(stdscr, "Saved", ".config / .config.mk / build/config.mk gerados.")
            continue
        if ch in (ord('l'), ord('L')):
            cfg = load_config()
            popup(stdscr, "Loaded", "Configuracao recarregada de .config")
            continue
        if ch in (ord('?'),):
            e = entries[idx] if entries else None
            if e and e.key:
                popup(stdscr, e.label, HELP.get(e.key, "Sem ajuda especifica."))
            else:
                popup(stdscr, "Help", "Use setas para navegar e Enter para selecionar.")
            continue

        if ch in (curses.KEY_RIGHT, ord('\n'), ord('\r'), ord(' '), ord('y'), ord('Y'), ord('n'), ord('N')) and entries:
            e = entries[idx]
            if e.kind == "submenu" and ch in (curses.KEY_RIGHT, ord('\n'), ord('\r')):
                stack.append(e.submenu or "root")
                continue
            if e.kind == "action" and ch in (ord('\n'), ord('\r')):
                if e.label.startswith("Save"):
                    write_outputs(cfg)
                    popup(stdscr, "Saved", ".config / .config.mk / build/config.mk gerados.")
                elif e.label.startswith("Load"):
                    cfg = load_config()
                    popup(stdscr, "Loaded", "Configuracao recarregada de .config")
                elif e.label.startswith("Exit"):
                    return cfg
                continue
            if e.kind == "bool" and e.key:
                if ch in (ord('y'), ord('Y')):
                    cfg[e.key] = "1"
                elif ch in (ord('n'), ord('N')):
                    cfg[e.key] = "0"
                else:
                    cfg[e.key] = "0" if cfg.get(e.key) == "1" else "1"
                cfg = normalize(cfg)
                continue
            if e.kind == "choice" and e.key:
                choices = CHOICE_KEYS[e.key]
                current = cfg.get(e.key, choices[0])
                try:
                    pos = choices.index(current)
                except ValueError:
                    pos = 0
                cfg[e.key] = choices[(pos + 1) % len(choices)]
                cfg = normalize(cfg)
                continue
            if e.kind == "string" and e.key and ch in (ord('\n'), ord('\r')):
                value = prompt_string(stdscr, e.label, cfg.get(e.key, ""))
                if e.key == "MSXBARE_ONE_ROM_PATH" and cfg.get("MSXBARE_ONE_ROM_MODE") == "1" and not value.strip():
                    popup(stdscr, "Invalid", "One ROM Mode exige One ROM path nao vazio.")
                else:
                    cfg[e.key] = value.strip()
                    cfg = normalize(cfg)
                continue


def main() -> int:
    parser = argparse.ArgumentParser(description="MSX BarePI menuconfig")
    parser.add_argument("--sync-only", action="store_true", help="sincroniza arquivos sem UI")
    parser.add_argument("--non-interactive", action="store_true", help="gera com valores atuais/default")
    args = parser.parse_args()

    os.chdir(ROOT)
    warn_workspace()
    cfg = load_config()

    no_tty = not sys.stdin.isatty() or not sys.stdout.isatty()
    if args.sync_only or args.non_interactive or os.getenv("NON_INTERACTIVE") == "1" or no_tty:
        write_outputs(cfg)
        return 0

    cfg = curses.wrapper(lambda stdscr: run_tui(stdscr, cfg))
    write_outputs(cfg)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
