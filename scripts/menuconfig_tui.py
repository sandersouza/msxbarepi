def warn_workspace() -> None:
    recommended = "/Users/sandersouza/Developer/msxbarepi-circle"
    cwd = os.getcwd()
    if cwd != recommended:
        print(f"[WARN] PWD atual: {cwd}", file=sys.stderr)
        print(f"[WARN] Recomenda-se usar {recommended}", file=sys.stderr)


def load_config() -> Dict[str, str]:
    cfg = dict(DEFAULTS)
    if os.path.isfile(CONFIG_FILE):
        with open(CONFIG_FILE, "r", encoding="utf-8") as f:
            for raw in f:
                line = raw.strip()
                if not line or line.startswith("#") or "=" not in line:
                    continue
                k, v = line.split("=", 1)
                k = k.strip()
                v = v.strip()
                if len(v) >= 2 and ((v[0] == "'" and v[-1] == "'") or (v[0] == '"' and v[-1] == '"')):
                    v = v[1:-1]
                if k in cfg:
                    cfg[k] = v
    return normalize(cfg)


def normalize(cfg: Dict[str, str]) -> Dict[str, str]:
    out = dict(cfg)
    for k in BOOL_KEYS:
        out[k] = "1" if out.get(k, "0") == "1" else "0"
    if out.get("MSXBARE_BOOT_MODE_DEFAULT") not in CHOICE_KEYS["MSXBARE_BOOT_MODE_DEFAULT"]:
        out["MSXBARE_BOOT_MODE_DEFAULT"] = "NORM"

    if out.get("MSXBARE_ONE_ROM_MODE") == "1":
        out["MSXBARE_FEAT_MSX2P"] = "1"
        out["MSXBARE_FEAT_LOAD_ROM"] = "0"
        out["MSXBARE_FEAT_LOAD_DISK"] = "0"
        out["MSXBARE_BOOT_MODE_DEFAULT"] = "GAME"
    return out


def write_outputs(cfg: Dict[str, str]) -> None:
    cfg = normalize(cfg)
    os.makedirs(os.path.join(ROOT, "build"), exist_ok=True)

    with open(CONFIG_FILE, "w", encoding="utf-8") as f:
        f.write("# Auto-generated by scripts/menuconfig_tui.py\n")
        for k in KEYS:
            f.write(f"{k}={shlex.quote(cfg.get(k, ''))}\n")

