#define MSXBARE_FEAT_FMPAC ${MSXBARE_FEAT_FMPAC}
#define MSXBARE_FEAT_DISK_ROM ${MSXBARE_FEAT_DISK_ROM}
#define MSXBARE_FEAT_MEGARAM ${MSXBARE_FEAT_MEGARAM}
#define MSXBARE_FEAT_MSX2 ${MSXBARE_FEAT_MSX2}
#define MSXBARE_BOOT_SCREEN ${MSXBARE_BOOT_SCREEN}
#define MSXBARE_FEAT_MSX2P ${MSXBARE_FEAT_MSX2P}
#define MSXBARE_FEAT_LOAD_ROM ${MSXBARE_FEAT_LOAD_ROM}
#define MSXBARE_FEAT_LOAD_DISK ${MSXBARE_FEAT_LOAD_DISK}
#define MSXBARE_ONE_ROM_MODE ${MSXBARE_ONE_ROM_MODE}
