#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT_DIR"

CONFIG_FILE=".config"
CONFIG_ROOT_MK=".config.mk"
CONFIG_MK="build/config.mk"
SYNC_ONLY=0
NON_INTERACTIVE="${NON_INTERACTIVE:-0}"

if [ "${1:-}" = "--sync-only" ]; then
  SYNC_ONLY=1
fi

if [ "$PWD" != "/Users/sandersouza/Developer/msxbarepi-circle" ]; then
  echo "[WARN] PWD atual: $PWD" >&2
  echo "[WARN] Recomenda-se usar /Users/sandersouza/Developer/msxbarepi-circle" >&2
fi

choose() {
  local prompt="$1"
  shift
  local options=("$@")

  if [ "$NON_INTERACTIVE" = "1" ]; then
    echo "${options[0]}"
    return 0
  fi

  if command -v fzf >/dev/null 2>&1; then
    local selected=""
    set +e
    selected="$(printf '%s\n' "${options[@]}" | fzf --height=12 --reverse --border --prompt "${prompt} > " --header "Setas + Enter | ESC = cancelar")"
    local status=$?
    set -e
    if [ "$status" -eq 0 ] && [ -n "$selected" ]; then
      echo "$selected"
      return 0
    fi
    return 1
  fi

  echo >&2
  echo "$prompt" >&2
  local i=1
  for opt in "${options[@]}"; do
    echo "  [$i] $opt" >&2
    i=$((i+1))
  done

  local sel
  while true; do
    printf "> " >&2
    read -r sel
    if [[ "$sel" =~ ^[0-9]+$ ]] && [ "$sel" -ge 1 ] && [ "$sel" -le "${#options[@]}" ]; then
      echo "${options[$((sel-1))]}"
      return 0
    fi
    echo "Selecao invalida." >&2
  done
}

yesno_to_num() {
  local value="$1"
  if [ "$value" = "ON" ] || [ "$value" = "1" ]; then
    echo "1"
  else
    echo "0"
  fi
}

num_to_yesno() {
  local value="$1"
  if [ "$value" = "1" ]; then
    echo "ON"
  else
    echo "OFF"
  fi
}

sanitize_num() {
  local value="$1"
  if [ "$value" = "1" ]; then
    echo "1"
  else
    echo "0"
  fi
}

write_shell_kv() {
  local key="$1"
  local value="$2"
  printf '%s=%q\n' "$key" "$value"
}

load_existing_config() {
  if [ -f "$CONFIG_FILE" ]; then
    # shellcheck disable=SC1090
    source "$CONFIG_FILE"
  fi
}

write_outputs() {
  mkdir -p build

  {
    echo "# Auto-generated by scripts/menuconfig.sh"
    write_shell_kv "DEBUG" "$DEBUG"
    write_shell_kv "MSXBARE_FEAT_SCC" "$MSXBARE_FEAT_SCC"
    write_shell_kv "MSXBARE_FEAT_FMPAC" "$MSXBARE_FEAT_FMPAC"
    write_shell_kv "MSXBARE_FEAT_DISK_ROM" "$MSXBARE_FEAT_DISK_ROM"
    write_shell_kv "MSXBARE_FEAT_MEGARAM" "$MSXBARE_FEAT_MEGARAM"
    write_shell_kv "MSXBARE_FEAT_MSX2" "$MSXBARE_FEAT_MSX2"
    write_shell_kv "MSXBARE_FEAT_MSX2P" "$MSXBARE_FEAT_MSX2P"
    write_shell_kv "MSXBARE_FEAT_LOAD_ROM" "$MSXBARE_FEAT_LOAD_ROM"
    write_shell_kv "MSXBARE_FEAT_LOAD_DISK" "$MSXBARE_FEAT_LOAD_DISK"
    write_shell_kv "MSXBARE_ONE_ROM_MODE" "$MSXBARE_ONE_ROM_MODE"
    write_shell_kv "MSXBARE_ONE_ROM_PATH" "$MSXBARE_ONE_ROM_PATH"
    write_shell_kv "MSXBARE_BOOT_MODE_DEFAULT" "$MSXBARE_BOOT_MODE_DEFAULT"
    write_shell_kv "MSXBARE_PATREON_TAG" "$MSXBARE_PATREON_TAG"
  } > "$CONFIG_FILE"

  {
    echo "# Auto-generated by scripts/menuconfig.sh"
    echo "DEBUG := $DEBUG"
    echo "MSXBARE_FEAT_SCC := $MSXBARE_FEAT_SCC"
    echo "MSXBARE_FEAT_FMPAC := $MSXBARE_FEAT_FMPAC"
    echo "MSXBARE_FEAT_DISK_ROM := $MSXBARE_FEAT_DISK_ROM"
    echo "MSXBARE_FEAT_MEGARAM := $MSXBARE_FEAT_MEGARAM"
    echo "MSXBARE_FEAT_MSX2 := $MSXBARE_FEAT_MSX2"
    echo "MSXBARE_FEAT_MSX2P := $MSXBARE_FEAT_MSX2P"
    echo "MSXBARE_FEAT_LOAD_ROM := $MSXBARE_FEAT_LOAD_ROM"
    echo "MSXBARE_FEAT_LOAD_DISK := $MSXBARE_FEAT_LOAD_DISK"
    echo "MSXBARE_ONE_ROM_MODE := $MSXBARE_ONE_ROM_MODE"
    echo "MSXBARE_ONE_ROM_PATH := $MSXBARE_ONE_ROM_PATH"
    echo "MSXBARE_BOOT_MODE_DEFAULT := $MSXBARE_BOOT_MODE_DEFAULT"
    echo "MSXBARE_PATREON_TAG := $MSXBARE_PATREON_TAG"
  } > "$CONFIG_ROOT_MK"

  cp "$CONFIG_ROOT_MK" "$CONFIG_MK"

  echo "Gerado: $CONFIG_FILE"
  echo "Gerado: $CONFIG_ROOT_MK"
  echo "Gerado: $CONFIG_MK"
}

# Defaults
DEBUG="1"
MSXBARE_FEAT_SCC="1"
MSXBARE_FEAT_FMPAC="1"
MSXBARE_FEAT_DISK_ROM="1"
MSXBARE_FEAT_MEGARAM="1"
MSXBARE_FEAT_MSX2="1"
MSXBARE_FEAT_MSX2P="1"
MSXBARE_FEAT_LOAD_ROM="1"
MSXBARE_FEAT_LOAD_DISK="1"
MSXBARE_ONE_ROM_MODE="0"
MSXBARE_ONE_ROM_PATH=""
MSXBARE_BOOT_MODE_DEFAULT="NORM"
MSXBARE_PATREON_TAG=""

load_existing_config

DEBUG="$(sanitize_num "${DEBUG:-1}")"
MSXBARE_FEAT_SCC="$(sanitize_num "${MSXBARE_FEAT_SCC:-1}")"
MSXBARE_FEAT_FMPAC="$(sanitize_num "${MSXBARE_FEAT_FMPAC:-1}")"
MSXBARE_FEAT_DISK_ROM="$(sanitize_num "${MSXBARE_FEAT_DISK_ROM:-1}")"
MSXBARE_FEAT_MEGARAM="$(sanitize_num "${MSXBARE_FEAT_MEGARAM:-1}")"
MSXBARE_FEAT_MSX2="$(sanitize_num "${MSXBARE_FEAT_MSX2:-1}")"
MSXBARE_FEAT_MSX2P="$(sanitize_num "${MSXBARE_FEAT_MSX2P:-1}")"
MSXBARE_FEAT_LOAD_ROM="$(sanitize_num "${MSXBARE_FEAT_LOAD_ROM:-1}")"
MSXBARE_FEAT_LOAD_DISK="$(sanitize_num "${MSXBARE_FEAT_LOAD_DISK:-1}")"
MSXBARE_ONE_ROM_MODE="$(sanitize_num "${MSXBARE_ONE_ROM_MODE:-0}")"
MSXBARE_ONE_ROM_PATH="${MSXBARE_ONE_ROM_PATH:-}"
MSXBARE_BOOT_MODE_DEFAULT="${MSXBARE_BOOT_MODE_DEFAULT:-NORM}"
MSXBARE_PATREON_TAG="${MSXBARE_PATREON_TAG:-}"

case "$MSXBARE_BOOT_MODE_DEFAULT" in
  NORM|FAST|GAME) ;;
  *) MSXBARE_BOOT_MODE_DEFAULT="NORM" ;;
esac

if [ "$SYNC_ONLY" = "1" ]; then
  write_outputs
  exit 0
fi

if [ "$NON_INTERACTIVE" = "1" ]; then
  write_outputs
  exit 0
fi

debug_choice="$(num_to_yesno "$DEBUG")"
scc_choice="$(num_to_yesno "$MSXBARE_FEAT_SCC")"
fmpac_choice="$(num_to_yesno "$MSXBARE_FEAT_FMPAC")"
disk_choice="$(num_to_yesno "$MSXBARE_FEAT_DISK_ROM")"
megaram_choice="$(num_to_yesno "$MSXBARE_FEAT_MEGARAM")"
msx2_choice="$(num_to_yesno "$MSXBARE_FEAT_MSX2")"
msx2p_choice="$(num_to_yesno "$MSXBARE_FEAT_MSX2P")"
load_rom_choice="$(num_to_yesno "$MSXBARE_FEAT_LOAD_ROM")"
load_disk_choice="$(num_to_yesno "$MSXBARE_FEAT_LOAD_DISK")"
one_rom_choice="$(num_to_yesno "$MSXBARE_ONE_ROM_MODE")"

set +e
debug_choice="$(choose 'Ativar DEBUG compilado' "$debug_choice" ON OFF)"; rc=$?
set -e; [ $rc -eq 0 ] || exit 1
set +e
scc_choice="$(choose 'Suporte a SCC' "$scc_choice" ON OFF)"; rc=$?
set -e; [ $rc -eq 0 ] || exit 1
set +e
fmpac_choice="$(choose 'Suporte a FM-PAC' "$fmpac_choice" ON OFF)"; rc=$?
set -e; [ $rc -eq 0 ] || exit 1
set +e
disk_choice="$(choose 'Suporte a DISK ROM' "$disk_choice" ON OFF)"; rc=$?
set -e; [ $rc -eq 0 ] || exit 1
set +e
megaram_choice="$(choose 'Suporte a MegaRAM' "$megaram_choice" ON OFF)"; rc=$?
set -e; [ $rc -eq 0 ] || exit 1
set +e
msx2_choice="$(choose 'Suporte a MSX2' "$msx2_choice" ON OFF)"; rc=$?
set -e; [ $rc -eq 0 ] || exit 1
set +e
msx2p_choice="$(choose 'Suporte a MSX2+' "$msx2p_choice" ON OFF)"; rc=$?
set -e; [ $rc -eq 0 ] || exit 1
set +e
load_rom_choice="$(choose 'Suporte a LOAD ROM' "$load_rom_choice" ON OFF)"; rc=$?
set -e; [ $rc -eq 0 ] || exit 1
set +e
load_disk_choice="$(choose 'Suporte a LOAD DISK' "$load_disk_choice" ON OFF)"; rc=$?
set -e; [ $rc -eq 0 ] || exit 1
set +e
MSXBARE_BOOT_MODE_DEFAULT="$(choose 'Boot Mode default compilado' "$MSXBARE_BOOT_MODE_DEFAULT" NORM FAST GAME)"; rc=$?
set -e; [ $rc -eq 0 ] || exit 1
set +e
one_rom_choice="$(choose 'One ROM Mode' "$one_rom_choice" OFF ON)"; rc=$?
set -e; [ $rc -eq 0 ] || exit 1

if [ "$one_rom_choice" = "ON" ]; then
  echo
  read -r -p "Caminho da ROM alvo para One ROM Mode (ex.: roms/games/GAME.ROM): " MSXBARE_ONE_ROM_PATH
  if [ -z "$MSXBARE_ONE_ROM_PATH" ]; then
    echo "[ERRO] One ROM Mode exige caminho de ROM." >&2
    exit 1
  fi
fi

echo
read -r -p "Tag Patreon/Owner (opcional, Enter para vazio): " MSXBARE_PATREON_TAG

DEBUG="$(yesno_to_num "$debug_choice")"
MSXBARE_FEAT_SCC="$(yesno_to_num "$scc_choice")"
MSXBARE_FEAT_FMPAC="$(yesno_to_num "$fmpac_choice")"
MSXBARE_FEAT_DISK_ROM="$(yesno_to_num "$disk_choice")"
MSXBARE_FEAT_MEGARAM="$(yesno_to_num "$megaram_choice")"
MSXBARE_FEAT_MSX2="$(yesno_to_num "$msx2_choice")"
MSXBARE_FEAT_MSX2P="$(yesno_to_num "$msx2p_choice")"
MSXBARE_FEAT_LOAD_ROM="$(yesno_to_num "$load_rom_choice")"
MSXBARE_FEAT_LOAD_DISK="$(yesno_to_num "$load_disk_choice")"
MSXBARE_ONE_ROM_MODE="$(yesno_to_num "$one_rom_choice")"

if [ "$MSXBARE_ONE_ROM_MODE" = "1" ]; then
  MSXBARE_FEAT_MSX2P="1"
  MSXBARE_FEAT_LOAD_ROM="0"
  MSXBARE_FEAT_LOAD_DISK="0"
  MSXBARE_BOOT_MODE_DEFAULT="GAME"
fi

write_outputs
